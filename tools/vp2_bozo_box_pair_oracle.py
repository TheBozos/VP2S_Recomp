"""Symbolic sequential evaluation of mod001 1f82c0 (VU0 macro box-box test).

Emits, for every EE compare (c.ole.s f1, f0 after SQC2 vf18 -> sp+10 and
SQC2 vf20 -> sp+0), the compared lane expressions as C++ using M(a,b) (ps2f
mul), A(a,b) (addNearest), S(a,b) (subNearest) and ABS(a).
Inputs: vf1..vf8 = R[r][l] rows (A: rows 0..3, B: rows 4..7), vf9 = sc[l],
vf10 = ca[l] (a0), vf11 = cb[l] (a2), vf24 = ea[l] (a1), vf25 = eb[l] (a3).
"""
import struct,sys
ELF=sys.argv[2] if len(sys.argv)>2 else "build_usa/elf/mod001.elf"
d=open(ELF,'rb').read()
ph=struct.unpack_from('<I',d,0x1c)[0];n=struct.unpack_from('<H',d,0x2c)[0]
segs=[struct.unpack_from('<6I',d,ph+32*i) for i in range(n)]
def word(a):
    for t,o,v,p,fs,ms in segs:
        if t==1 and v<=a<v+fs:return struct.unpack_from('<I',d,o+a-v)[0]
ONE='0x3f800000u';ZERO='0u'
vf=[[None]*4 for _ in range(32)];vf[0]=[ZERO,ZERO,ZERO,ONE]
for r in range(8):vf[1+r]=[f'R[{r}][{l}]' for l in range(4)]
vf[9]=[f'sc[{l}]' for l in range(4)]
acc=[None]*4
mem={}
def M(a,b):return f'M({a},{b})'
def A(a,b):return f'A({a},{b})'
def S(a,b):return f'S({a},{b})'
def lanes(w):return [l for l,b in enumerate((8,4,2,1)) if (w>>21)&b]
out=[];stores={}
pc=0x1f82c4
loads={(4,):'ca',(6,):'cb',(5,):'ea',(7,):'eb'}
while pc<0x1f8838:
    w=word(pc);op=w>>26
    if op==0x36:
        base=(w>>21)&31;t=(w>>16)&31;name={4:'ca',6:'cb',5:'ea',7:'eb'}[base]
        vf[t]=[f'{name}[{l}]' for l in range(4)]
    elif op==0x3e:
        t=(w>>16)&31;base=(w>>21)&31
        stores[{3:'hi',2:'lo'}[base]]=list(vf[t])
    elif op==0x31:   # lwc1
        off=w&0xffff;rt=(w>>16)&31
        if rt==1:hi=stores['hi'][(off-0x10)//4]
        else:lo=stores['lo'][off//4];out.append((pc,hi,lo))
    elif op==0x12 and w&(1<<25):
        f=w&63;ft=(w>>16)&31;fs=(w>>11)&31;fd=(w>>6)&31;L=lanes(w)
        if f>=0x3c:
            sub=((w>>6)&31)<<2|(f&3)
            if sub in (0x18,0x19,0x1a,0x1b):   # MULAbc
                bc=sub&3
                for l in L:acc[l]=M(vf[fs][l],vf[ft][bc])
            elif sub in (0x08,0x09,0x0a,0x0b):  # MADDAbc
                bc=sub&3
                for l in L:acc[l]=A(acc[l],M(vf[fs][l],vf[ft][bc]))
            elif sub in (0x0c,0x0d,0x0e,0x0f):  # MSUBAbc
                bc=sub&3
                for l in L:acc[l]=S(acc[l],M(vf[fs][l],vf[ft][bc]))
            elif sub==0x29:   # MADDA
                for l in L:acc[l]=A(acc[l],M(vf[fs][l],vf[ft][l]))
            elif sub==0x2a:   # MULA
                for l in L:acc[l]=M(vf[fs][l],vf[ft][l])
            elif sub==0x1d:   # ABS ft = |fs|
                new=list(vf[ft])
                for l in L:new[l]=f'ABS({vf[fs][l]})'
                vf[ft]=new
            elif sub==0x2f:pass
            else:raise SystemExit('unhandled special %x at %x'%(sub,pc))
        else:
            new=list(vf[fd])
            if f<0x1c:
                kind=f>>2;bc=f&3
                for l in L:
                    b=vf[ft][bc]
                    if kind==0:new[l]=A(vf[fs][l],b)
                    elif kind==1:new[l]=S(vf[fs][l],b)
                    elif kind==2:new[l]=A(acc[l],M(vf[fs][l],b))
                    elif kind==3:new[l]=S(acc[l],M(vf[fs][l],b))
                    elif kind==6:new[l]=M(vf[fs][l],b)
                    else:raise SystemExit('unhandled bc op %x at %x'%(f,pc))
            elif f==0x28:
                for l in L:new[l]=A(vf[fs][l],vf[ft][l])
            elif f==0x2c:
                for l in L:new[l]=S(vf[fs][l],vf[ft][l])
            elif f==0x2a:
                for l in L:new[l]=M(vf[fs][l],vf[ft][l])
            elif f==0x29:
                for l in L:new[l]=A(acc[l],M(vf[fs][l],vf[ft][l]))
            else:raise SystemExit('unhandled op %x at %x'%(f,pc))
            vf[fd]=new
    pc+=4
mode=sys.argv[1] if len(sys.argv)>1 else 'list'
if mode=='list':
    for pc,hi,lo in out:print('%x'%pc,'\n  |T.L| ',hi,'\n  r     ',lo)
else:
    print('// Generated by tools/vp2_bozo_box_pair_oracle.py from mod001 1f82c0 (sequential VU0 macro semantics).')
    print('// Each pair: the lane compared at sp+10 (separation) and sp+0 (radius); the')
    print('// routine returns 0 at the first pair with separation > radius, else 1.')
    print('const uint32_t pairs[%d][2]={'%len(out))
    for pc,hi,lo in out:print('  {%s,\n   %s},'%(hi,lo))
    print('};')
print('// %d compares'%len(out),file=sys.stderr)
