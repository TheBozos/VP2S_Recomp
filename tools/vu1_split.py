#!/usr/bin/env python3
"""A lifted VU1 program (tools/vu1_lift.py's output) too big for MSVC to compile as one function, cut into pieces.

The lifted function declares every register and counter first, then runs as labelled blocks joined by gotos, then
stores the registers back (its `done:` block). Its parameters and those declarations become the members of a struct
(the same names, the same initialisers), each run of blocks becomes a member function of that struct in a file of its
own, a goto that leaves its piece returns the label it goes to, and the function itself runs the pieces one after the
other from its entry. The blocks' code is not changed. Only the instance the registration uses (<true>) is built.
  tools/vu1_split.py <file.cpp>... [--out <dir>] [--lines 15000]: each file to <dir>/<file stem>/ (default: split/
  next to the file), the original removed.
"""
import argparse
import os
import re
import sys

SIGNATURE = re.compile(r'^    uint64_t (\w+)\((uint32_t entry, VU1State &state, uint8_t \*data, uint32_t top, Vu1Kick out, void \*user)\)$')
LABEL = re.compile(r'^        n(\d+):$')
GOTO = re.compile(r'goto (n(\d+)|done);')
ENTRY = re.compile(r'case (0x[0-9a-fA-F]+u): goto n(\d+);')
DONE = 0xFFFFFFFF
UNKNOWN = 0xFFFFFFFE


def split(text, stem, out_dir, lines_per_piece=15000):
    lines = text.split('\n')
    sig = next(i for i, line in enumerate(lines) if SIGNATURE.match(line))
    name, params = SIGNATURE.match(lines[sig]).groups()
    assert lines[sig - 1].strip() == 'template <bool kSticky>' and lines[sig + 1] == '    {'
    switch = next(i for i in range(sig, len(lines)) if lines[i] == '        switch (entry)')
    prologue = lines[sig + 2:switch]
    entry_end = next(i for i in range(switch, len(lines)) if lines[i] == '        }')
    entries = [ENTRY.search(line).groups() for line in lines[switch:entry_end] if ENTRY.search(line)]
    done = next(i for i in range(entry_end, len(lines)) if lines[i] == '    done:')
    body = lines[entry_end + 1:done]
    close = next(i for i in range(done, len(lines)) if lines[i] == '    }')
    epilogue = lines[done + 1:close]
    registration = lines[next(i for i in range(close, len(lines)) if lines[i].startswith('#include "vp2s_vu1_programs.h"')):]

    # Pieces of about lines_per_piece lines, cut where a block starts.
    pieces, start = [], 0
    while start < len(body):
        end = min(start + lines_per_piece, len(body))
        while end < len(body) and not LABEL.match(body[end]):
            end += 1
        pieces.append(body[start:end])
        start = end
    labels = [[int(m.group(1)) for m in map(LABEL.match, piece) if m] for piece in pieces]
    piece_of = {label: k for k, own in enumerate(labels) for label in own}
    assert len(pieces) < 256

    os.makedirs(out_dir, exist_ok=True)
    ctx = f'{name}_ctx'
    header = ['#pragma once', '// Generated by tools/vu1_split.py from tools/vu1_lift.py output: game code, never committed.',
              '#include "runtime/ps2_vu1_lifted_ops.h"', '', 'namespace ps2x::vu1lift', '{', '    template <bool kSticky>',
              f'    struct {ctx}', '    {', '        uint32_t entry;', '        VU1State &state;', '        uint8_t *data;',
              '        uint32_t top;', '        Vu1Kick out;', '        void *user;']
    header += prologue
    header += [f'        static constexpr uint32_t kNodeDone = {DONE:#x}u, kNodeUnknown = {UNKNOWN:#x}u;']
    header += [f'        uint32_t piece{k}(uint32_t node);' for k in range(len(pieces))]
    header += ['        uint64_t finish();', '    };', '}', '']
    with open(os.path.join(out_dir, f'{stem}.h'), 'w', newline='\n') as f:
        f.write('\n'.join(header))

    files = [f'{stem}.h']
    for k, piece in enumerate(pieces):
        own = set(labels[k])

        def jump(match, own=own):
            if match.group(1) == 'done':
                return 'return kNodeDone;'
            label = int(match.group(2))
            return match.group(0) if label in own else f'return {label}u;'

        out = [f'#include "{stem}.h"', '', 'namespace ps2x::vu1lift', '{', '    template <bool kSticky>',
               f'    uint32_t {ctx}<kSticky>::piece{k}(uint32_t node)', '    {', '        switch (node)', '        {']
        out += [f'        case {label}u: goto n{label};' for label in labels[k]]
        out += ['        default: return kNodeUnknown;', '        }']
        out += [GOTO.sub(jump, line).replace('return kUnknownTarget;', 'return kNodeUnknown;') for line in piece]
        following = labels[k + 1][0] if k + 1 < len(pieces) else None
        out += [f'        return {following}u;' if following is not None else '        return kNodeDone;', '    }', '',
                f'    template uint32_t {ctx}<true>::piece{k}(uint32_t node);', '}', '']
        file = f'{stem}_{k:02d}.cpp'
        with open(os.path.join(out_dir, file), 'w', newline='\n') as f:
            f.write('\n'.join(out))
        files.append(file)

    main = [f'#include "{stem}.h"', '', 'namespace ps2x::vu1lift', '{', '    template <bool kSticky>',
            f'    uint64_t {ctx}<kSticky>::finish()', '    {']
    main += epilogue
    table = [str(piece_of.get(label, 255)) for label in range(max(piece_of) + 1)]
    main += ['    }', '', '    // The piece each block is in, by label.', '    static const uint8_t kPieceOf[] = {']
    main += ['        ' + ', '.join(table[i:i + 40]) + ',' for i in range(0, len(table), 40)]
    main += ['    };', '', '    template <bool kSticky>', f'    uint64_t {name}({params})', '    {',
             f'        {ctx}<kSticky> c{{entry, state, data, top, out, user}};', '        uint32_t node = 0;',
             '        switch (entry)', '        {']
    main += [f'        case {pc}: node = {label}u; break;' for pc, label in entries]
    main += ['        default: return 0;', '        }', '        for (;;)', '        {',
             f'            if (node == {ctx}<kSticky>::kNodeDone)', '                return c.finish();',
             f'            if (node == {ctx}<kSticky>::kNodeUnknown)', '                return kUnknownTarget;']
    main += ['            const uint32_t k = node < sizeof(kPieceOf) ? kPieceOf[node] : 0xFFu;']
    main += ['            switch (k)', '            {']
    main += [f'            case {k}: node = c.piece{k}(node); break;' for k in range(len(pieces))]
    main += [f'            default: return kUnknownTarget;']
    main += ['            }', '        }', '    }', '', f'    template uint64_t {name}<true>({params});', '}', '']
    main += registration
    with open(os.path.join(out_dir, f'{stem}.cpp'), 'w', newline='\n') as f:
        f.write('\n'.join(main))
    files.append(f'{stem}.cpp')
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('files', nargs='+')
    ap.add_argument('--out', help='parent directory of the pieces (default: split/ next to each file)')
    ap.add_argument('--lines', type=int, default=15000)
    a = ap.parse_args()
    for path in a.files:
        stem = os.path.splitext(os.path.basename(path))[0]
        parent = a.out or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(path))) if os.path.basename(os.path.dirname(os.path.abspath(path))) == 'big' else os.path.dirname(os.path.abspath(path)), 'split')
        files = split(open(path).read(), stem, os.path.join(parent, stem), a.lines)
        os.remove(path)
        print(f'{path}: {len(files) - 2} pieces -> {os.path.join(parent, stem)}')


if __name__ == '__main__':
    sys.exit(main())
